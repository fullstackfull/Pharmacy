import {BASE, SHOTS, loginAdmin, watch, hasServerError} from './_env.mjs';
import {chromium} from 'playwright';
const browser = await chromium.launch({executablePath: '/opt/pw-browsers/chromium'});
const page = await browser.newPage({viewport: {width: 1600, height: 1200}});
await page.emulateMedia({reducedMotion: 'reduce'});
const problems = watch(page);
await loginAdmin(page);
const res = await page.goto(BASE + '/admin/analytics', {waitUntil: 'domcontentloaded'});
console.log('GET /admin/analytics ->', res.status());
if (await hasServerError(page)) problems.push('analytics rendered a server error');
await page.waitForTimeout(900);
await page.evaluate(() => document.querySelectorAll('.phpdebugbar,.modal,.modal-backdrop,.alert--container').forEach(n => n.remove()));
const body = await page.locator('.content').innerText();
const empties = (body.match(/No data|no data|No campaign|No device|No source/g) || []).length;
console.log('empty-state phrases on the page:', empties);
await page.screenshot({path: SHOTS + '/analytics-before.png', fullPage: true});
console.log(problems.length ? 'PROBLEMS:\n' + problems.join('\n') : 'ok');
await browser.close();
