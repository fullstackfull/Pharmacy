import {BASE, SHOTS, loginAdmin} from './_env.mjs';
import {chromium} from 'playwright';
const browser = await chromium.launch({executablePath: '/opt/pw-browsers/chromium'});
const page = await browser.newPage({viewport: {width: 1600, height: 1100}});
await loginAdmin(page);
await page.goto(BASE + '/admin/monitoring/network', {waitUntil: 'domcontentloaded'});
await page.waitForTimeout(1200);
await page.goto(BASE + '/admin/monitoring/network', {waitUntil: 'domcontentloaded'});
await page.waitForTimeout(1500);
await page.evaluate(() => document.querySelectorAll('.phpdebugbar').forEach(n => n.remove()));
const text = await page.locator('.mon-main').innerText();
const cut = text.indexOf('Tcp\n');
console.log(text.slice(cut));
await page.screenshot({path: SHOTS + '/monitoring-network.png', fullPage: true});
await browser.close();
